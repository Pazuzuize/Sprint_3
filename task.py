import datetime

class OnlineSalesRegisterCollector:

    def __init__(self):
        self.__name_items = []
        self.__number_items = 0
        self.__item_price = {'чипсы': 50, 'кола': 100, 'печенье': 45, 'молоко': 55, 'кефир': 70}
        self.__tax_rate = {'чипсы': 20, 'кола': 20, 'печенье': 20, 'молоко': 10, 'кефир': 10}


    #Геттер для получения списка названий товаров
    @property
    def name_items(self):
        return self.__name_items
    

    #Геттер для получения количества товаров
    @property
    def number_items(self):
        return self.__number_items


    #Метод добавляет товары в чек
    def add_item_to_cheque(self, name):
        if len(name) == 0 or len(name) > 40:
            raise ValueError('Нельзя добавить товар, если в его названии нет символов или их больше 40')
        
        if name not in self.__item_price:
            raise NameError('Позиция отсутствует в товарном справочнике')
        
        self.__name_items.append(name)
        self.__number_items += 1


    #Метод убирает товары из чека
    def delete_item_from_check(self, name):
        if name not in self.__name_items:
            raise NameError('Позиция отсутствует в чеке')
        
        self.__name_items.remove(name)
        self.__number_items -= 1


    #Метод считает общую сумму покупок
    def check_amount(self):
        total = []
        for item in self.__name_items:
            total.append(self.__item_price[item])
        
        amount = sum(total)

        # Применяем скидку 10%
        if len(self.__name_items) > 10:
            return amount * 0.9
        
        return amount


    #Метод рассчитывает НДС товаров, у которых налоговая ставка 20%
    def twenty_percent_tax_calculation(self):
        twenty_percent_tax = []
        total = []
        
        for item in self.__name_items:
            if self.__tax_rate[item] == 20:
                twenty_percent_tax.append(item)
                total.append(self.__item_price[item])
        
        #Рассчитываем базовую сумму НДС
        tax_amount = sum(total) * 0.2
        
        #Если в чеке больше 10 товаров, применяем скидку ко всей сумме
        if len(self.__name_items) > 10:
            #Скидка 10% применяется ко всей сумме чека, включая НДС,
            #Но НДС рассчитывается от стоимости товаров до применения скидки,
            #Поэтому скидка влияет на итоговый размер НДС
            return tax_amount * 0.9
        else:
            return tax_amount


    #Метод рассчитывает НДС товаров, у которых ставка 10%
    def ten_percent_tax_calculation(self):
        ten_percent_tax = []
        total = []
        
        for item in self.__name_items:
            if self.__tax_rate[item] == 10:
                ten_percent_tax.append(item)
                total.append(self.__item_price[item])
        
        #Рассчитываем базовую сумму НДС
        tax_amount = sum(total) * 0.1
        
        #Если в чеке больше 10 товаров, применяем скидку ко всей сумме
        if len(self.__name_items) > 10:
            #Скидка 10% применяется ко всей сумме чека, включая НДС,
            #Но НДС рассчитывается от стоимости товаров до применения скидки,
            #Поэтому скидка влияет на итоговый размер НДС
            return tax_amount * 0.9
        else:
            return tax_amount


    #Метод возвращает общую сумму НДС по чеку
    def total_tax(self):
        return self.ten_percent_tax_calculation() + self.twenty_percent_tax_calculation()


    #Метод возвращает номер телефона покупателя
    @staticmethod
    def get_telephone_number(telephone_number):
        try:
            #Проверяем, можно ли преобразовать в число
            int(telephone_number)
        except (ValueError, TypeError):
            raise ValueError('Необходимо ввести цифры')
        
        #Преобразуем в строку для проверки длины
        str_number = str(telephone_number)
        
        if len(str_number) != 10:
            raise ValueError('Необходимо ввести 10 цифр после "+7"')
        
        #Возвращаем полный номер телефона
        return f"+7{str_number}"


    #Метод возвращает дату и время покупки
    @staticmethod
    def get_date_and_time():
        import datetime
        
        date_and_time = []
        now = datetime.datetime.now()
        
        date = [
            ['часы', lambda x: x.hour],
            ['минуты', lambda x: x.minute],
            ['день', lambda x: x.day],
            ['месяц', lambda x: x.month],
            ['год', lambda x: x.year]
        ]
        
        for item in date:
            interval_name = item[0]
            interval_func = item[1]
            date_and_time.append(f'{interval_name}: {interval_func(now)}')
        
        return date_and_time